  const length = path.getTotalLength();
  const { duration, delay, ease } = getLineDrawOptions(path);

  gsap.killTweensOf(path);
  gsap.set(path, {
    strokeDasharray: length,
    strokeDashoffset: length,
  });

  gsapTweens.push(
    gsap.to(path, {
      strokeDashoffset: 0,
      duration,
      delay,
      ease,
    }),
  );
};

const initLineDrawAnimations = () => {
  if (typeof IntersectionObserver === "undefined") return;

  const paths = schemeRef.value?.querySelectorAll<SVGPathElement>(".line-left-right");
  if (!paths?.length) return;

  lineRevealObserver?.disconnect();

  lineRevealObserver = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          animateLinePath(entry.target as SVGPathElement);
        }
      });
    },
    {
      threshold: 0.1,
      rootMargin: "0px 0px -5% 0px",
    },
  );

  paths.forEach((path) => {
    resetLinePath(path);
    lineRevealObserver?.observe(path);
  });
};

const resetTextElement = (element: HTMLElement) => {
  const offset = parseDrawNumber(
    element.dataset.textOffset,
    TEXT_ANIM_DEFAULTS.offset,
  );
  const fromBottom = element.classList.contains("text-anim-up");
  const startY = fromBottom ? offset : -offset;

  delete element.dataset.textAnimated;
  gsap.killTweensOf(element);
  gsap.set(element, { clearProps: "opacity,transform" });
  gsap.set(element, { opacity: 0, y: startY });
};

const animateTextElement = (element: HTMLElement) => {
  if (element.dataset.textAnimated === "true") return;

  element.dataset.textAnimated = "true";
  textRevealObserver?.unobserve(element);

  const duration = parseDrawNumber(
    element.dataset.textDuration,
    TEXT_ANIM_DEFAULTS.duration,
  );
  const delay = parseDrawNumber(
    element.dataset.textDelay,
    TEXT_ANIM_DEFAULTS.delay,
  );
  const offset = parseDrawNumber(
    element.dataset.textOffset,
    TEXT_ANIM_DEFAULTS.offset,
  );
  const ease = element.dataset.textEase || TEXT_ANIM_DEFAULTS.ease;
  const fromBottom = element.classList.contains("text-anim-up");
  const startY = fromBottom ? offset : -offset;

  gsap.killTweensOf(element);
  gsap.set(element, { opacity: 0, y: startY });

  gsapTweens.push(
    gsap.to(element, {
      opacity: 1,
      y: 0,
      duration,
      delay,
      ease,
    }),
  );
};

const initTextAnimations = () => {
  if (typeof IntersectionObserver === "undefined") return;

  const elements = pageRef.value?.querySelectorAll<HTMLElement>(
    ".text-anim, .text-anim-up",
  );
  if (!elements?.length) return;

  textRevealObserver?.disconnect();

  textRevealObserver = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          animateTextElement(entry.target as HTMLElement);
        }
      });
    },
    {
      threshold: 0.15,
      rootMargin: "0px 0px -8% 0px",
    },
  );

  elements.forEach((element) => {
    resetTextElement(element);
    textRevealObserver?.observe(element);
  });
};

const cleanupPageAnimations = () => {
  textRevealObserver?.disconnect();
  textRevealObserver = null;

  lineRevealObserver?.disconnect();
  lineRevealObserver = null;

  gsapTweens.forEach((tween) => tween.kill());
  gsapTweens.length = 0;

  pageRef.value
    ?.querySelectorAll<HTMLElement>(".text-anim, .text-anim-up")
    .forEach((element) => {
      resetTextElement(element);
    });

  schemeRef.value
    ?.querySelectorAll<SVGPathElement>(".line-left-right")
    .forEach((path) => {
      resetLinePath(path);
    });
};

const runPageAnimations = async () => {
  await nextTick();
  cleanupPageAnimations();
  initLineDrawAnimations();
  initTextAnimations();
};

onMounted(() => {
  runPageAnimations();
});

onBeforeUnmount(() => {
  cleanupPageAnimations();
});

if (import.meta.hot) {
  import.meta.hot.dispose(() => {
    cleanupPageAnimations();
  });

  import.meta.hot.on("vite:afterUpdate", () => {
    runPageAnimations();
  });
}
</script>

