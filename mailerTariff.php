<?php

declare(strict_types=1);

/**
 * ============================================================
 * CODESEVEN.RU
 * ОБРАБОТЧИК ЗАЯВКИ НА ТАРИФ
 * ============================================================
 *
 * Назначение файла:
 *
 * Этот обработчик принимает данные формы выбора тарифа SMM,
 * выполняет серверную проверку полученных значений и отправляет
 * информацию о заявке на корпоративную электронную почту.
 *
 *
 * ------------------------------------------------------------
 * ВАЖНО О ТЕКУЩЕЙ ЛОГИКЕ САЙТА
 * ------------------------------------------------------------
 *
 * На текущем этапе JavaScript сайта работает следующим образом:
 *
 * 1. Посетитель заполняет форму тарифа.
 *
 * 2. JavaScript отправляет данные в mailerTariff.php.
 *
 * 3. Если обработчик возвращает:
 *
 *        {
 *            "success": true
 *        }
 *
 *    клиентская часть запускает функцию generateQR().
 *
 * 4. generateQR() обращается к api/payment.php и начинает
 *    процесс создания платежа.
 *
 * Поэтому этот обработчик пока сохраняет существующий формат
 * ответа, чтобы не нарушить работу клиентской части сайта.
 *
 *
 * ------------------------------------------------------------
 * ПОЛЯ, КОТОРЫЕ ПРИХОДЯТ ИЗ ФОРМЫ
 * ------------------------------------------------------------
 *
 * name
 *     Имя клиента.
 *
 * phone
 *     Телефон клиента.
 *
 * email
 *     Электронная почта клиента.
 *
 * package
 *     Название выбранного тарифа.
 *
 * price
 *     Цена, которую передала клиентская часть.
 *
 *
 * ------------------------------------------------------------
 * ВАЖНО О ЦЕНЕ
 * ------------------------------------------------------------
 *
 * Полю price из браузера доверять нельзя.
 *
 * Посетитель может вручную изменить HTML, JavaScript или сам
 * HTTP-запрос и передать любую сумму.
 *
 * Поэтому mailerTariff.php использует price только как
 * информационное значение.
 *
 * Настоящую стоимость платежа позже будет определять только
 * серверная логика api/payment.php.
 *
 *
 * ------------------------------------------------------------
 * БЕЗОПАСНОСТЬ
 * ------------------------------------------------------------
 *
 * В этом файле отсутствуют:
 *
 * - SMTP-пароль;
 * - платёжные ключи;
 * - другие секретные данные.
 *
 * Они находятся в локальном .env, который исключён из Git.
 *
 * Все общие настройки приложения загружаются через
 * bootstrap.php.
 * ============================================================
 */

use PHPMailer\PHPMailer\Exception;
use PHPMailer\PHPMailer\PHPMailer;


/**
 * ============================================================
 * ПОДКЛЮЧАЕМ ОБЩУЮ ИНИЦИАЛИЗАЦИЮ
 * ============================================================
 *
 * bootstrap.php:
 *
 * - подключает Composer;
 * - загружает .env;
 * - предоставляет env() и env_required().
 */
require_once __DIR__ . '/bootstrap.php';


/**
 * ============================================================
 * НАСТРАИВАЕМ HTTP-ОТВЕТ
 * ============================================================
 *
 * JavaScript сайта ожидает JSON.
 */
header('Content-Type: application/json; charset=utf-8');


/**
 * ============================================================
 * ВСПОМОГАТЕЛЬНАЯ ФУНКЦИЯ JSON-ОТВЕТА
 * ============================================================
 *
 * @param bool   $success Успешно ли выполнена операция.
 * @param string $message Сообщение для клиентской части.
 * @param int    $httpCode HTTP-код ответа.
 *
 * @return never
 */
function sendTariffJsonResponse(
    bool $success,
    string $message,
    int $httpCode = 200
): never {
    http_response_code($httpCode);

    echo json_encode(
        [
            'success' => $success,
            'message' => $message,
        ],
        JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES
    );

    exit;
}


/**
 * ============================================================
 * РАЗРЕШАЕМ ТОЛЬКО POST
 * ============================================================
 *
 * Заявка создаётся только через POST-запрос.
 */
if ($_SERVER['REQUEST_METHOD'] !== 'POST') {
    sendTariffJsonResponse(
        false,
        'Метод запроса не поддерживается.',
        405
    );
}


/**
 * ============================================================
 * ПОЛУЧАЕМ ДАННЫЕ ФОРМЫ
 * ============================================================
 *
 * Каждое значение:
 *
 * 1. Проверяется на существование через ??.
 * 2. Приводится к строке.
 * 3. Очищается от пробелов по краям через trim().
 */
$name = trim((string) ($_POST['name'] ?? ''));
$phone = trim((string) ($_POST['phone'] ?? ''));
$email = trim((string) ($_POST['email'] ?? ''));
$tariff = trim((string) ($_POST['package'] ?? ''));
$clientPrice = trim((string) ($_POST['price'] ?? ''));


/**
 * ============================================================
 * РАЗРЕШЁННЫЕ ТАРИФЫ
 * ============================================================
 *
 * Название тарифа также нельзя безоговорочно принимать
 * от браузера.
 *
 * Пользователь может изменить значение hidden-поля,
 * поэтому проверяем тариф по серверному белому списку.
 *
 * ВАЖНО:
 *
 * Здесь намеренно пока НЕ храним цены.
 *
 * Единственным источником истины для цены позже станет
 * api/payment.php.
 */
$allowedTariffs = [
    'Базовый пакет',
    'Средний пакет',
    'Полный пакет',
];


/**
 * ============================================================
 * ВАЛИДАЦИЯ ОБЯЗАТЕЛЬНЫХ ПОЛЕЙ
 * ============================================================
 */


/**
 * Проверяем имя.
 */
if ($name === '') {
    sendTariffJsonResponse(
        false,
        'Пожалуйста, укажите имя.'
    );
}


/**
 * Проверяем телефон.
 */
if ($phone === '') {
    sendTariffJsonResponse(
        false,
        'Пожалуйста, укажите номер телефона.'
    );
}


/**
 * Проверяем электронную почту.
 */
if ($email === '') {
    sendTariffJsonResponse(
        false,
        'Пожалуйста, укажите электронную почту.'
    );
}


/**
 * Проверяем формат электронной почты.
 *
 * FILTER_VALIDATE_EMAIL выполняет стандартную серверную
 * проверку email-адреса.
 */
if (filter_var($email, FILTER_VALIDATE_EMAIL) === false) {
    sendTariffJsonResponse(
        false,
        'Указан некорректный адрес электронной почты.'
    );
}


/**
 * Проверяем наличие выбранного тарифа.
 */
if ($tariff === '') {
    sendTariffJsonResponse(
        false,
        'Не выбран тариф.'
    );
}


/**
 * Проверяем тариф по серверному белому списку.
 *
 * Третий параметр true включает строгое сравнение типов.
 */
if (!in_array($tariff, $allowedTariffs, true)) {
    sendTariffJsonResponse(
        false,
        'Выбран неизвестный тариф.'
    );
}


/**
 * ============================================================
 * ОГРАНИЧИВАЕМ РАЗМЕР ВХОДНЫХ ДАННЫХ
 * ============================================================
 *
 * Публичные формы необходимо ограничивать по размеру, чтобы
 * через них нельзя было отправлять огромные строки.
 */
if (strlen($name) > 300) {
    sendTariffJsonResponse(
        false,
        'Указано слишком длинное имя.'
    );
}

if (strlen($phone) > 100) {
    sendTariffJsonResponse(
        false,
        'Указан некорректный номер телефона.'
    );
}

if (strlen($email) > 320) {
    sendTariffJsonResponse(
        false,
        'Адрес электронной почты слишком длинный.'
    );
}

if (strlen($tariff) > 200) {
    sendTariffJsonResponse(
        false,
        'Название тарифа слишком длинное.'
    );
}


/**
 * ============================================================
 * ПОДГОТАВЛИВАЕМ ДАННЫЕ ДЛЯ HTML-ПИСЬМА
 * ============================================================
 *
 * Значения пользователя нельзя вставлять напрямую внутрь HTML.
 *
 * htmlspecialchars() предотвращает интерпретацию HTML-тегов,
 * переданных посетителем.
 */
$safeName = htmlspecialchars(
    $name,
    ENT_QUOTES | ENT_SUBSTITUTE,
    'UTF-8'
);

$safePhone = htmlspecialchars(
    $phone,
    ENT_QUOTES | ENT_SUBSTITUTE,
    'UTF-8'
);

$safeEmail = htmlspecialchars(
    $email,
    ENT_QUOTES | ENT_SUBSTITUTE,
    'UTF-8'
);

$safeTariff = htmlspecialchars(
    $tariff,
    ENT_QUOTES | ENT_SUBSTITUTE,
    'UTF-8'
);


/**
 * Цена отображается только как дополнительная информация.
 *
 * Она НЕ используется здесь для определения настоящей суммы
 * платежа.
 */
$safeClientPrice = htmlspecialchars(
    $clientPrice,
    ENT_QUOTES | ENT_SUBSTITUTE,
    'UTF-8'
);


/**
 * ============================================================
 * ЗАГРУЖАЕМ SMTP-НАСТРОЙКИ
 * ============================================================
 *
 * Все значения берутся из .env.
 */
try {
    $smtpHost = env_required('SMTP_HOST');
    $smtpPort = (int) env_required('SMTP_PORT');
    $smtpUsername = env_required('SMTP_USERNAME');
    $smtpPassword = env_required('SMTP_PASSWORD');

    $smtpEncryption = env('SMTP_ENCRYPTION', 'ssl') ?? 'ssl';
} catch (Throwable $exception) {
    /**
     * Подробности ошибки сохраняем только в журнале сервера.
     */
    error_log(
        sprintf(
            '[CodeSeven][mailerTariff.php] Ошибка конфигурации SMTP: %s',
            $exception->getMessage()
        )
    );

    sendTariffJsonResponse(
        false,
        'Сервис отправки заявок временно недоступен.',
        500
    );
}


/**
 * ============================================================
 * СОЗДАЁМ PHPMAILER
 * ============================================================
 */
$mail = new PHPMailer(true);


try {
    /**
     * ========================================================
     * НАСТРОЙКА SMTP
     * ========================================================
     */

    $mail->isSMTP();

    $mail->Host = $smtpHost;
    $mail->SMTPAuth = true;

    $mail->Username = $smtpUsername;
    $mail->Password = $smtpPassword;

    $mail->SMTPSecure = $smtpEncryption;
    $mail->Port = $smtpPort;


    /**
     * ========================================================
     * КОДИРОВКА ПИСЬМА
     * ========================================================
     */

    $mail->CharSet = 'UTF-8';
    $mail->Encoding = 'base64';


    /**
     * ========================================================
     * ОТПРАВИТЕЛЬ
     * ========================================================
     *
     * Используем тот же адрес, через который происходит
     * SMTP-аутентификация.
     */
    $mail->setFrom(
        $smtpUsername,
        'CodeSeven — заявка на тариф'
    );


    /**
     * ========================================================
     * ПОЛУЧАТЕЛЬ
     * ========================================================
     *
     * Пока заявки отправляются на SMTP-адрес.
     *
     * Позже адрес получателя можно вынести в SMTP_TO_ADDRESS.
     */
    $mail->addAddress($smtpUsername);


    /**
     * ========================================================
     * HTML-ФОРМАТ
     * ========================================================
     */
    $mail->isHTML(true);


    /**
     * Исправляем опечатку старой версии:
     *
     * было:
     * "Новая заявкак SMM тарифа"
     *
     * стало:
     * "Новая заявка на SMM-тариф"
     */
    $mail->Subject = 'Новая заявка на SMM-тариф';


    /**
     * ========================================================
     * HTML-ТЕЛО ПИСЬМА
     * ========================================================
     */
    $mail->Body = <<<HTML
<h2>Новая заявка на SMM-тариф</h2>

<p>
    <strong>Имя:</strong><br>
    {$safeName}
</p>

<p>
    <strong>Телефон:</strong><br>
    {$safePhone}
</p>

<p>
    <strong>E-mail:</strong><br>
    {$safeEmail}
</p>

<p>
    <strong>Выбранный тариф:</strong><br>
    {$safeTariff}
</p>

<p>
    <strong>Цена, переданная клиентской частью:</strong><br>
    {$safeClientPrice}
</p>

<p>
    <em>
        Примечание: сумма, переданная браузером, является
        информационной. Настоящая стоимость должна определяться
        сервером при создании платежа.
    </em>
</p>
HTML;


    /**
     * ========================================================
     * ТЕКСТОВАЯ ВЕРСИЯ ПИСЬМА
     * ========================================================
     */
    $mail->AltBody =
        "Новая заявка на SMM-тариф\n\n" .
        "Имя: {$name}\n" .
        "Телефон: {$phone}\n" .
        "E-mail: {$email}\n" .
        "Тариф: {$tariff}\n" .
        "Цена из браузера: {$clientPrice}\n";


    /**
     * ========================================================
     * ОТПРАВЛЯЕМ ПИСЬМО
     * ========================================================
     */
    $mail->send();


    /**
     * ========================================================
     * УСПЕШНЫЙ ОТВЕТ
     * ========================================================
     *
     * Сохраняем существующий интерфейс:
     *
     * data.success === true
     *
     * После этого common.js запускает generateQR().
     */
    sendTariffJsonResponse(
        true,
        'Заявка успешно отправлена.'
    );

} catch (Exception $exception) {
    /**
     * ========================================================
     * ОШИБКА ОТПРАВКИ
     * ========================================================
     *
     * Подробную SMTP-ошибку отправляем только в error_log().
     */
    error_log(
        sprintf(
            '[CodeSeven][mailerTariff.php] Ошибка отправки письма: %s',
            $mail->ErrorInfo
        )
    );

    sendTariffJsonResponse(
        false,
        'Не удалось отправить заявку. Попробуйте ещё раз позже.',
        500
    );
}
