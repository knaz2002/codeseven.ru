<?php

declare(strict_types=1);

/**
 * ============================================================
 * CODESEVEN.RU
 * ОБРАБОТЧИК ОСНОВНОЙ ФОРМЫ ОБРАТНОЙ СВЯЗИ
 * ============================================================
 *
 * Назначение файла:
 *
 * Этот PHP-скрипт принимает данные, отправленные посетителем
 * через основную форму обратной связи сайта CodeSeven,
 * проверяет полученные значения и отправляет письмо
 * на корпоративную электронную почту через SMTP.
 *
 *
 * ------------------------------------------------------------
 * КАКИЕ ДАННЫЕ ПРИХОДЯТ ИЗ ФОРМЫ
 * ------------------------------------------------------------
 *
 * Клиентская часть сайта отправляет POST-запрос со следующими
 * полями:
 *
 * name
 *     Имя посетителя.
 *
 * phone
 *     Номер телефона посетителя.
 *
 * message
 *     Дополнительное сообщение посетителя.
 *
 *
 * ------------------------------------------------------------
 * ФОРМАТ ОТВЕТА
 * ------------------------------------------------------------
 *
 * Обработчик всегда возвращает данные в формате JSON.
 *
 * Пример успешного ответа:
 *
 * {
 *     "success": true,
 *     "message": "Сообщение успешно отправлено."
 * }
 *
 * Пример ответа при ошибке:
 *
 * {
 *     "success": false,
 *     "message": "Не удалось отправить сообщение."
 * }
 *
 *
 * ------------------------------------------------------------
 * БЕЗОПАСНОСТЬ
 * ------------------------------------------------------------
 *
 * ВАЖНО:
 *
 * В этом файле НЕТ:
 *
 * - SMTP-пароля;
 * - логина почты, записанного непосредственно в PHP-коде;
 * - ключей API;
 * - других секретных значений.
 *
 * Все секретные параметры загружаются из файла .env.
 *
 * Сам файл .env добавлен в .gitignore и поэтому не должен
 * попадать в GitHub.
 *
 * Для загрузки .env используется общий bootstrap.php.
 * ============================================================
 */

use PHPMailer\PHPMailer\Exception;
use PHPMailer\PHPMailer\PHPMailer;


/**
 * ============================================================
 * ПОДКЛЮЧЕНИЕ БАЗОВОЙ ИНИЦИАЛИЗАЦИИ ПРИЛОЖЕНИЯ
 * ============================================================
 *
 * bootstrap.php:
 *
 * 1. Подключает vendor/autoload.php от Composer.
 * 2. Загружает переменные окружения из .env.
 * 3. Предоставляет функции env() и env_required().
 */
require_once __DIR__ . '/bootstrap.php';


/**
 * ============================================================
 * НАСТРОЙКА HTTP-ОТВЕТА
 * ============================================================
 *
 * JavaScript сайта ожидает JSON.
 *
 * Явно указываем Content-Type, чтобы браузер и клиентская
 * часть корректно интерпретировали ответ сервера.
 */
header('Content-Type: application/json; charset=utf-8');


/**
 * ============================================================
 * ВСПОМОГАТЕЛЬНАЯ ФУНКЦИЯ ДЛЯ ОТПРАВКИ JSON-ОТВЕТА
 * ============================================================
 *
 * Эта функция позволяет не повторять json_encode() во всех
 * ветках обработчика.
 *
 * @param bool   $success Успешно ли выполнена операция.
 * @param string $message Текст ответа для клиентской части.
 * @param int    $httpCode HTTP-код ответа.
 *
 * @return never
 */
function sendJsonResponse(
    bool $success,
    string $message,
    int $httpCode = 200
): never {
    /**
     * Устанавливаем HTTP-код ответа до вывода тела.
     */
    http_response_code($httpCode);

    /**
     * JSON_UNESCAPED_UNICODE нужен для того, чтобы русские
     * буквы оставались читаемыми в JSON и не преобразовывались
     * в последовательности вида \u041e\u0448...
     */
    echo json_encode(
        [
            'success' => $success,
            'message' => $message,
        ],
        JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES
    );

    /**
     * После формирования ответа обработчик больше не должен
     * выполнять никакой код.
     */
    exit;
}


/**
 * ============================================================
 * ПРОВЕРКА HTTP-МЕТОДА
 * ============================================================
 *
 * Этот обработчик предназначен исключительно для отправки
 * данных формы методом POST.
 *
 * Открытие mailer.php напрямую через браузер создаёт GET-запрос
 * и не должно приводить к попытке отправки письма.
 */
if ($_SERVER['REQUEST_METHOD'] !== 'POST') {
    sendJsonResponse(
        false,
        'Метод запроса не поддерживается.',
        405
    );
}


/**
 * ============================================================
 * ПОЛУЧЕНИЕ ДАННЫХ ФОРМЫ
 * ============================================================
 *
 * Используем оператор ??, чтобы отсутствие поля в POST-запросе
 * не вызывало предупреждение PHP.
 *
 * Каждое значение явно преобразуем в строку.
 *
 * trim() удаляет лишние пробелы в начале и конце.
 */
$name = trim((string) ($_POST['name'] ?? ''));
$phone = trim((string) ($_POST['phone'] ?? ''));
$message = trim((string) ($_POST['message'] ?? ''));


/**
 * ============================================================
 * ПРОВЕРКА ОБЯЗАТЕЛЬНЫХ ПОЛЕЙ
 * ============================================================
 *
 * Нельзя полагаться только на JavaScript-валидацию.
 *
 * Любой человек или бот может обратиться к mailer.php напрямую,
 * минуя HTML-форму и JavaScript сайта.
 *
 * Поэтому обязательная проверка всегда выполняется также
 * непосредственно на сервере.
 */


/**
 * Имя обязательно.
 *
 * Пока возвращаем HTTP 200 при пользовательской ошибке,
 * поскольку существующий JavaScript сайта сначала проверяет
 * response.ok.
 *
 * Позже мы отдельно переработаем JS и сможем использовать
 * полноценный HTTP 422 для ошибок валидации.
 */
if ($name === '') {
    sendJsonResponse(
        false,
        'Пожалуйста, укажите имя.'
    );
}


/**
 * Телефон также является обязательным полем.
 */
if ($phone === '') {
    sendJsonResponse(
        false,
        'Пожалуйста, укажите номер телефона.'
    );
}


/**
 * ============================================================
 * ОГРАНИЧЕНИЕ РАЗМЕРА ВХОДНЫХ ДАННЫХ
 * ============================================================
 *
 * Публичная форма потенциально может использоваться ботами.
 *
 * Ограничения не являются полноценной антиспам-защитой,
 * однако не позволяют отправлять через форму неограниченно
 * большие объёмы текста.
 */


/**
 * Имя не должно быть чрезмерно длинным.
 */
if (strlen($name) > 300) {
    sendJsonResponse(
        false,
        'Указано слишком длинное имя.'
    );
}


/**
 * Для телефонного номера устанавливаем достаточно большой
 * лимит, чтобы поддерживать различные международные форматы,
 * но одновременно не принимать огромные строки.
 */
if (strlen($phone) > 100) {
    sendJsonResponse(
        false,
        'Указан некорректный номер телефона.'
    );
}


/**
 * Ограничиваем произвольное сообщение размером 10 000 байт.
 *
 * Для обычной формы обратной связи этого более чем достаточно.
 */
if (strlen($message) > 10000) {
    sendJsonResponse(
        false,
        'Сообщение слишком длинное.'
    );
}


/**
 * ============================================================
 * ПОДГОТОВКА ДАННЫХ ДЛЯ HTML-ПИСЬМА
 * ============================================================
 *
 * Нельзя вставлять пользовательский ввод непосредственно
 * внутрь HTML-письма.
 *
 * Например, злоумышленник может попытаться передать:
 *
 * <script>...</script>
 *
 * или другую HTML-разметку.
 *
 * htmlspecialchars() преобразует специальные HTML-символы
 * в безопасное текстовое представление.
 */


/**
 * Безопасная версия имени.
 */
$safeName = htmlspecialchars(
    $name,
    ENT_QUOTES | ENT_SUBSTITUTE,
    'UTF-8'
);


/**
 * Безопасная версия телефонного номера.
 */
$safePhone = htmlspecialchars(
    $phone,
    ENT_QUOTES | ENT_SUBSTITUTE,
    'UTF-8'
);


/**
 * Безопасная версия сообщения.
 */
$safeMessage = htmlspecialchars(
    $message,
    ENT_QUOTES | ENT_SUBSTITUTE,
    'UTF-8'
);


/**
 * Сохраняем переносы строк посетителя при отображении
 * сообщения внутри HTML-письма.
 */
$safeMessageHtml = nl2br($safeMessage);


/**
 * ============================================================
 * ЗАГРУЗКА SMTP-НАСТРОЕК
 * ============================================================
 *
 * Значения берутся из .env через функции bootstrap.php.
 *
 * env_required() применяется для параметров, без которых
 * отправить письмо невозможно.
 *
 * Если обязательный параметр отсутствует или пустой,
 * функция выбрасывает RuntimeException.
 */
try {
    $smtpHost = env_required('SMTP_HOST');
    $smtpPort = (int) env_required('SMTP_PORT');
    $smtpUsername = env_required('SMTP_USERNAME');
    $smtpPassword = env_required('SMTP_PASSWORD');

    /**
     * Тип шифрования имеет значение по умолчанию ssl.
     *
     * Для текущей конфигурации Timeweb обычно используется:
     *
     * SSL + порт 465.
     */
    $smtpEncryption = env('SMTP_ENCRYPTION', 'ssl') ?? 'ssl';
} catch (Throwable $exception) {
    /**
     * Подробности конфигурационной ошибки записываем только
     * в серверный лог.
     *
     * Посетителю сайта не нужно знать:
     *
     * - какие переменные окружения отсутствуют;
     * - какой SMTP используется;
     * - внутреннюю структуру сервера.
     */
    error_log(
        sprintf(
            '[CodeSeven][mailer.php] Ошибка конфигурации SMTP: %s',
            $exception->getMessage()
        )
    );

    sendJsonResponse(
        false,
        'Сервис отправки сообщений временно недоступен.',
        500
    );
}


/**
 * ============================================================
 * СОЗДАНИЕ ОБЪЕКТА PHPMAILER
 * ============================================================
 *
 * Параметр true включает режим исключений.
 *
 * В таком режиме PHPMailer выбрасывает исключение при ошибке,
 * которое мы можем корректно перехватить через try/catch.
 */
$mail = new PHPMailer(true);


try {
    /**
     * ========================================================
     * НАСТРОЙКА SMTP
     * ========================================================
     */

    /**
     * Сообщаем PHPMailer, что письмо необходимо отправлять
     * через внешний SMTP-сервер.
     */
    $mail->isSMTP();


    /**
     * Адрес SMTP-сервера.
     *
     * Значение приходит из:
     *
     * SMTP_HOST
     */
    $mail->Host = $smtpHost;


    /**
     * Включаем SMTP-аутентификацию.
     */
    $mail->SMTPAuth = true;


    /**
     * Логин почтового ящика.
     */
    $mail->Username = $smtpUsername;


    /**
     * Пароль почтового ящика.
     *
     * ВАЖНО:
     * пароль существует только в памяти во время выполнения
     * PHP-скрипта и не записан в исходный код.
     */
    $mail->Password = $smtpPassword;


    /**
     * Тип защищённого соединения.
     */
    $mail->SMTPSecure = $smtpEncryption;


    /**
     * SMTP-порт.
     */
    $mail->Port = $smtpPort;


    /**
     * ========================================================
     * КОДИРОВКА
     * ========================================================
     *
     * Явно используем UTF-8, поскольку сайт, имя клиента,
     * тема письма и само сообщение могут содержать кириллицу.
     */
    $mail->CharSet = 'UTF-8';


    /**
     * Base64 помогает корректно передавать содержимое письма
     * с кириллицей через различные почтовые серверы.
     */
    $mail->Encoding = 'base64';


    /**
     * ========================================================
     * ОТПРАВИТЕЛЬ
     * ========================================================
     *
     * Адрес From совпадает с SMTP-учётной записью.
     *
     * Это уменьшает вероятность проблем с политиками SPF,
     * DKIM и настройками почтового сервера.
     */
    $mail->setFrom(
        $smtpUsername,
        'CodeSeven — форма сайта'
    );


    /**
     * ========================================================
     * ПОЛУЧАТЕЛЬ
     * ========================================================
     *
     * Пока заявка отправляется на тот же корпоративный адрес,
     * который используется для SMTP.
     *
     * В дальнейшем при необходимости мы вынесем адрес
     * получателя в отдельную переменную SMTP_TO_ADDRESS.
     */
    $mail->addAddress($smtpUsername);


    /**
     * ========================================================
     * ФОРМАТ ПИСЬМА
     * ========================================================
     *
     * Разрешаем HTML-разметку в теле письма.
     */
    $mail->isHTML(true);


    /**
     * Тема сообщения.
     */
    $mail->Subject = 'Новая заявка с сайта CodeSeven';


    /**
     * ========================================================
     * HTML-ВЕРСИЯ ПИСЬМА
     * ========================================================
     *
     * Здесь используются только предварительно экранированные
     * значения $safeName, $safePhone и $safeMessageHtml.
     */
    $mail->Body = <<<HTML
<h2>Новая заявка с формы обратной связи</h2>

<p>
    <strong>Имя:</strong><br>
    {$safeName}
</p>

<p>
    <strong>Телефон:</strong><br>
    {$safePhone}
</p>

<p>
    <strong>Сообщение:</strong><br>
    {$safeMessageHtml}
</p>
HTML;


    /**
     * ========================================================
     * ТЕКСТОВАЯ ВЕРСИЯ ПИСЬМА
     * ========================================================
     *
     * Некоторые почтовые клиенты или системы безопасности
     * могут не отображать HTML.
     *
     * Поэтому у письма должна быть альтернативная обычная
     * текстовая версия.
     */
    $mail->AltBody =
        "Новая заявка с формы обратной связи\n\n" .
        "Имя: {$name}\n" .
        "Телефон: {$phone}\n" .
        "Сообщение: {$message}";


    /**
     * ========================================================
     * ОТПРАВКА ПИСЬМА
     * ========================================================
     *
     * Если SMTP-сервер вернёт ошибку, PHPMailer выбросит
     * исключение и выполнение перейдёт в catch ниже.
     */
    $mail->send();


    /**
     * ========================================================
     * УСПЕШНЫЙ ОТВЕТ
     * ========================================================
     *
     * Формат остаётся совместимым с существующим common.js,
     * который проверяет data.success.
     */
    sendJsonResponse(
        true,
        'Сообщение успешно отправлено.'
    );

} catch (Exception $exception) {
    /**
     * ========================================================
     * ОШИБКА ОТПРАВКИ
     * ========================================================
     *
     * Технические подробности записываем в системный журнал.
     *
     * Никогда не отправляем посетителю сайта:
     *
     * - SMTP ErrorInfo;
     * - пароль;
     * - внутренние пути;
     * - stack trace;
     * - настройки сервера.
     */
    error_log(
        sprintf(
            '[CodeSeven][mailer.php] Ошибка отправки письма: %s',
            $mail->ErrorInfo
        )
    );

    sendJsonResponse(
        false,
        'Не удалось отправить сообщение. Попробуйте ещё раз позже.',
        500
    );
}
