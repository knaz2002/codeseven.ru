<?php

declare(strict_types=1);

/**
 * ============================================================
 * CODESEVEN.RU — БАЗОВАЯ ИНИЦИАЛИЗАЦИЯ PHP-ПРИЛОЖЕНИЯ
 * ============================================================
 *
 * Этот файл подключается серверными PHP-скриптами проекта
 * перед выполнением основной бизнес-логики.
 *
 * Здесь выполняются общие действия, которые должны быть
 * одинаковыми для всех PHP-обработчиков:
 *
 * 1. Подключается автозагрузчик Composer.
 * 2. Загружаются переменные окружения из файла .env.
 * 3. Определяются вспомогательные функции для безопасного
 *    чтения настроек приложения.
 *
 * ВАЖНО:
 *
 * Файл .env содержит реальные пароли, ключи API и другие
 * секретные данные и поэтому НЕ хранится в Git.
 *
 * В репозитории находится только .env.example, который
 * показывает структуру необходимых параметров без настоящих
 * секретов.
 * ============================================================
 */

use Dotenv\Dotenv;


/**
 * ------------------------------------------------------------
 * Подключение автозагрузчика Composer.
 * ------------------------------------------------------------
 *
 * Composer автоматически загружает установленные библиотеки,
 * например:
 *
 * - PHPMailer;
 * - phpdotenv.
 *
 * Благодаря этому больше не требуется вручную подключать
 * файлы PHPMailer.php, SMTP.php и Exception.php.
 */

$autoloadPath = __DIR__ . '/vendor/autoload.php';

if (!is_file($autoloadPath)) {
    throw new RuntimeException(
        'Не найден vendor/autoload.php. Выполните команду composer install.'
    );
}

require_once $autoloadPath;


/**
 * ------------------------------------------------------------
 * Загрузка файла .env.
 * ------------------------------------------------------------
 *
 * createImmutable() загружает переменные окружения, но не
 * перезаписывает существующие переменные операционной системы.
 *
 * Это важно для production:
 *
 * если в будущем секреты будут задаваться непосредственно
 * через системное окружение сервера, они получат приоритет
 * перед локальным файлом .env.
 *
 * safeLoad() выбран специально вместо load():
 *
 * - локально файл .env обычно существует;
 * - на production переменные могут задаваться иным способом;
 * - отсутствие .env не должно само по себе приводить
 *   к аварийному завершению всего приложения.
 */

$dotenv = Dotenv::createImmutable(__DIR__);
$dotenv->safeLoad();


/**
 * Получает строковую переменную окружения.
 *
 * Функция централизует работу с настройками приложения,
 * чтобы по всему проекту не использовать напрямую $_ENV,
 * $_SERVER и getenv().
 *
 * @param string      $name    Название переменной окружения.
 * @param string|null $default Значение по умолчанию.
 *
 * @return string|null
 */
function env(string $name, ?string $default = null): ?string
{
    /**
     * phpdotenv помещает значения в массив $_ENV.
     */
    if (array_key_exists($name, $_ENV)) {
        return (string) $_ENV[$name];
    }

    /**
     * Дополнительно проверяем реальные переменные окружения
     * операционной системы.
     */
    $value = getenv($name);

    if ($value !== false) {
        return (string) $value;
    }

    return $default;
}


/**
 * Получает обязательную переменную окружения.
 *
 * Используется для параметров, без которых выполнение
 * операции невозможно, например SMTP-пароля или ключа
 * платёжной системы.
 *
 * Вместо тихого использования пустой строки приложение
 * немедленно сообщает разработчику о неправильной настройке.
 *
 * @param string $name Название обязательной переменной.
 *
 * @return string
 *
 * @throws RuntimeException
 */
function env_required(string $name): string
{
    $value = env($name);

    if ($value === null || trim($value) === '') {
        throw new RuntimeException(
            sprintf(
                'Не задана обязательная переменная окружения "%s".',
                $name
            )
        );
    }

    return $value;
}
